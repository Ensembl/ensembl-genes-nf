#!/usr/bin/env python3
"""Generate SQL that reassigns every core stable ID from registry ranges."""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

import pymysql

from stable_id_mapping.ids import (
    StableIdRange,
    exon_range_from_gene_range,
    parse_id_range,
)
from stable_id_mapping.outputs import (
    sql_identifier,
    sql_string,
    write_values_insert,
)
from stable_id_mapping.range_check import (
    check_stable_id,
    find_duplicate_stable_ids,
)


FEATURE_TABLES = {
    "gene": ("gene", "gene_id"),
    "transcript": ("transcript", "transcript_id"),
    "translation": ("translation", "translation_id"),
    "exon": ("exon", "exon_id"),
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db-name", required=True)
    parser.add_argument("--gene-range", type=parse_id_range, required=True)
    parser.add_argument("--transcript-range", type=parse_id_range, required=True)
    parser.add_argument("--translation-range", type=parse_id_range, required=True)
    parser.add_argument("--output-sql", type=Path, required=True)
    parser.add_argument("--dry-run-sql", type=Path, required=True)
    parser.add_argument("--output-json", type=Path, required=True)
    parser.add_argument("--batch-size", type=int, default=500)
    parser.add_argument(
        "--backup-prefix",
        default=(
            "stable_id_reassignment_backup_"
            + datetime.now().strftime("%Y%m%d_%H%M%S")
        ),
    )
    return parser.parse_args()


def connect_read_only(db_name: str):
    return pymysql.connect(
        host=os.environ["GBS1"],
        port=int(os.environ["GBP1"]),
        user="ensro",
        password="",
        database=db_name,
        cursorclass=pymysql.cursors.DictCursor,
    )


def load_current_features(db_name: str) -> dict[str, list[dict]]:
    populations: dict[str, list[dict]] = {}
    connection = connect_read_only(db_name)

    try:
        with connection.cursor() as cursor:
            for feature_type, (table_name, primary_key) in FEATURE_TABLES.items():
                cursor.execute(
                    f"SELECT {primary_key} AS feature_id, "
                    "stable_id, COALESCE(version, 0) AS version "
                    f"FROM {table_name} "
                    f"ORDER BY {primary_key}"
                )
                populations[feature_type] = list(cursor.fetchall())
    finally:
        connection.close()

    return populations


def format_range(id_range: StableIdRange) -> str:
    return (
        f"{id_range.prefix}:"
        f"{id_range.start:011d}-{id_range.end:011d}"
    )


def generate_assignments(
    populations: dict[str, list[dict]],
    ranges: dict[str, StableIdRange],
) -> dict[str, list[tuple[int, str]]]:
    assignments: dict[str, list[tuple[int, str]]] = {}

    for feature_type, rows in populations.items():
        id_range = ranges[feature_type]
        required = len(rows)
        available = id_range.end - id_range.start + 1

        if required > available:
            raise RuntimeError(
                f"Registry range exhausted; feature type: {feature_type}; "
                f"required={required}, available={available}, "
                f"range={format_range(id_range)}"
            )

        assignments[feature_type] = [
            (
                row["feature_id"],
                f"{id_range.prefix}{id_range.start + index:011d}",
            )
            for index, row in enumerate(rows)
        ]

    return assignments


def write_noop_sql(
    path: Path,
    db_name: str,
    dry_run: bool,
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    with path.open("w", encoding="utf-8") as handle:
        handle.write("-- Generated by stable_id_mapping.\n")
        handle.write("-- Registry range check passed.\n")
        handle.write("-- No stable-ID reassignment is required.\n")
        if dry_run:
            handle.write("-- Dry-run SQL: no changes to preview.\n")
        handle.write(f"\nUSE {sql_identifier(db_name)};\n")


def write_reassignment_sql(
    path: Path,
    db_name: str,
    assignments: dict[str, list[tuple[int, str]]],
    batch_size: int,
    backup_prefix: str,
    dry_run: bool,
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    with path.open("w", encoding="utf-8") as handle:
        handle.write("-- Generated by stable_id_mapping.\n")
        handle.write("-- Full stable-ID reassignment from registry ranges.\n")
        handle.write("-- Review all counts before execution.\n\n")
        handle.write(f"USE {sql_identifier(db_name)};\n\n")

        if not dry_run:
            for feature_type, (table_name, _primary_key) in FEATURE_TABLES.items():
                backup_table = f"{backup_prefix}_{table_name}"
                handle.write(
                    f"CREATE TABLE {sql_identifier(backup_table)} "
                    f"AS SELECT * FROM {sql_identifier(table_name)};\n"
                )
            handle.write("\n")

        handle.write("START TRANSACTION;\n\n")

        for feature_type, rows in assignments.items():
            table_name, primary_key = FEATURE_TABLES[feature_type]
            update_table = f"tmp_stable_id_reassign_{feature_type}"

            handle.write(
                f"CREATE TEMPORARY TABLE {sql_identifier(update_table)} (\n"
                "  feature_id BIGINT NOT NULL,\n"
                "  new_stable_id VARCHAR(128) NOT NULL,\n"
                "  PRIMARY KEY (feature_id),\n"
                "  UNIQUE KEY (new_stable_id)\n"
                ");\n\n"
            )

            write_values_insert(
                handle,
                sql_identifier(update_table),
                ["feature_id", "new_stable_id"],
                [
                    [
                        str(feature_id),
                        sql_string(new_stable_id),
                    ]
                    for feature_id, new_stable_id in rows
                ],
                batch_size,
            )

            handle.write(
                f"SELECT {sql_string(feature_type)} AS type,\n"
                "       COUNT(*) AS assignment_count\n"
                f"FROM {sql_identifier(update_table)};\n\n"
            )
            
            handle.write(
                f"SELECT {sql_string(feature_type)} AS type,\n"
                "       COUNT(*) AS matched_count\n"
                f"FROM {sql_identifier(table_name)} f\n"
                f"JOIN {sql_identifier(update_table)} u "
                f"ON f.{sql_identifier(primary_key)} = u.feature_id;\n\n"
            )

            handle.write(
                f"SELECT f.{sql_identifier(primary_key)} AS feature_id,\n"
                "       f.stable_id AS current_stable_id,\n"
                "       f.version AS current_version,\n"
                "       u.new_stable_id,\n"
                "       1 AS new_version\n"
                f"FROM {sql_identifier(table_name)} f\n"
                f"JOIN {sql_identifier(update_table)} u "
                f"ON f.{sql_identifier(primary_key)} = u.feature_id\n"
                f"ORDER BY f.{sql_identifier(primary_key)}\n"
                "LIMIT 20;\n\n"
            )

            if dry_run:
                continue

            handle.write(
                f"UPDATE {sql_identifier(table_name)} f\n"
                f"JOIN {sql_identifier(update_table)} u "
                f"ON f.{sql_identifier(primary_key)} = u.feature_id\n"
                f"SET f.stable_id = CONCAT("
                f"{sql_string(f'__tmp_reassign_{feature_type}_')}, "
                f"f.{sql_identifier(primary_key)}),\n"
                "    f.version = 0;\n\n"
            )

            handle.write(
                f"UPDATE {sql_identifier(table_name)} f\n"
                f"JOIN {sql_identifier(update_table)} u "
                f"ON f.{sql_identifier(primary_key)} = u.feature_id\n"
                "SET f.stable_id = u.new_stable_id,\n"
                "    f.version = 1;\n\n"
            )

        handle.write("ROLLBACK;\n" if dry_run else "COMMIT;\n")


def write_summary(path: Path, summary: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def main() -> int:
    args = parse_args()

    if args.batch_size < 1:
        raise ValueError("batch-size must be >= 1")

    ranges = {
        "gene": args.gene_range,
        "transcript": args.transcript_range,
        "translation": args.translation_range,
        "exon": exon_range_from_gene_range(args.gene_range),
    }

    populations = load_current_features(args.db_name)

    all_stable_ids = [
        row["stable_id"]
        for rows in populations.values()
        for row in rows
    ]
    duplicates = find_duplicate_stable_ids(all_stable_ids)

    if duplicates:
        write_summary(
            args.output_json,
            {
                "db_name": args.db_name,
                "status": "fatal_duplicates",
                "duplicate_count": len(duplicates),
                "duplicate_examples": list(duplicates[:20]),
            },
        )
        sys.stderr.write(
            "\n*** FATAL: DUPLICATE STABLE IDs DETECTED ***\n"
            f"Database: {args.db_name}\n"
            f"Duplicate IDs: {len(duplicates)}\n"
        )
        return 2

    feature_summaries: dict[str, dict] = {}
    total_agreeing = 0
    total_disagreeing = 0

    for feature_type, rows in populations.items():
        reason_counts = Counter(
            check_stable_id(
                row["stable_id"],
                ranges[feature_type],
            ).reason
            for row in rows
        )

        agreeing = reason_counts["agrees"]
        disagreeing = len(rows) - agreeing
        total_agreeing += agreeing
        total_disagreeing += disagreeing

        feature_summaries[feature_type] = {
            "total": len(rows),
            "agreeing": agreeing,
            "disagreeing": disagreeing,
            "reason_counts": dict(sorted(reason_counts.items())),
        }

    if total_disagreeing == 0:
        write_noop_sql(args.output_sql, args.db_name, dry_run=False)
        write_noop_sql(args.dry_run_sql, args.db_name, dry_run=True)

        write_summary(
            args.output_json,
            {
                "db_name": args.db_name,
                "status": "clean",
                "features": feature_summaries,
            },
        )

        print(
            f"{args.db_name}: all stable IDs agree with registry allocations"
        )
        return 0

    if total_agreeing:
        sys.stderr.write(
            "\n*** WARNING: MIXED STABLE-ID POPULATION DETECTED ***\n"
            "Some identifiers already agree with the registry, but a full "
            "reassignment will still be generated.\n"
        )

    try:
        assignments = generate_assignments(populations, ranges)
    except RuntimeError as exc:
        write_summary(
            args.output_json,
            {
                "db_name": args.db_name,
                "status": "fatal_range_exhausted",
                "error": str(exc),
                "features": feature_summaries,
            },
        )
        sys.stderr.write(
            "\n*** FATAL: REGISTRY RANGE EXHAUSTED ***\n"
            f"{exc}\n"
        )
        return 2

    write_reassignment_sql(
        args.output_sql,
        args.db_name,
        assignments,
        args.batch_size,
        args.backup_prefix,
        dry_run=False,
    )
    write_reassignment_sql(
        args.dry_run_sql,
        args.db_name,
        assignments,
        args.batch_size,
        args.backup_prefix,
        dry_run=True,
    )

    write_summary(
        args.output_json,
        {
            "db_name": args.db_name,
            "status": "reassignment_generated",
            "total_rows": sum(len(rows) for rows in populations.values()),
            "features": feature_summaries,
            "assignments": {
                feature_type: len(rows)
                for feature_type, rows in assignments.items()
            },
            "output_sql": str(args.output_sql),
            "dry_run_sql": str(args.dry_run_sql),
        },
    )

    sys.stderr.write(
        "\n*** FULL STABLE-ID REASSIGNMENT SQL GENERATED ***\n"
        f"Database: {args.db_name}\n"
        f"Rows: {sum(len(rows) for rows in populations.values())}\n"
        "The SQL has not been executed.\n"
    )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
